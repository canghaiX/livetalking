const {chromium} = require(process.env.PLAYWRIGHT_MODULE || '/tmp/livetalking-browser/node_modules/playwright');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror',error=>errors.push(error.message));
  const base = process.env.BROWSER_BASE || 'http://127.0.0.1:8021';
  await page.goto(base+'/avatar-package.html');
  await page.waitForFunction(()=>document.querySelector('#serviceState').textContent.includes('就绪'));
  await page.getByRole('button',{name:'＋ 新建角色包'}).click();
  await page.locator('[name=name]').fill('网页验收角色');
  const packageId = 'browser_test_'+Date.now();
  await page.locator('[name=package_id]').fill(packageId);
  for (let index=0;index<4;index++) await page.locator('.draft-row button:not([disabled])').last().click();
  await page.getByRole('button',{name:'＋ 添加动作'}).click();
  await page.locator('.draft-row').last().locator('input').nth(0).fill('listening');
  await page.locator('.draft-row').last().locator('input').nth(1).fill('倾听等待');
  await page.getByRole('button',{name:'创建角色包',exact:true}).click();
  await page.waitForFunction(id=>document.querySelector('#packageId').textContent===id,packageId);
  const neutral = page.locator('[data-id=neutral_explain]');
  const listening = page.locator('[data-id=listening]');
  await neutral.locator('input[type=file]').setInputFiles(path.join(__dirname,'test-valid.mp4'));
  await neutral.locator('input[type=checkbox]').check();
  await neutral.getByRole('button',{name:'↑ 上传解析'}).click();
  await page.waitForFunction(()=>document.querySelector('[data-id=neutral_explain] strong').textContent==='已完成',null,{timeout:90000});
  await listening.locator('input[type=file]').setInputFiles(path.join(__dirname,'test-invalid-fps.mp4'));
  await listening.locator('input[type=checkbox]').check();
  await listening.getByRole('button',{name:'↑ 上传解析'}).click();
  await page.waitForFunction(()=>document.querySelector('[data-id=listening] .error').textContent.includes('25fps'),null,{timeout:30000});
  await page.screenshot({path:path.join(__dirname,'test-desktop.png'),fullPage:true});
  await listening.locator('input[type=file]').setInputFiles(path.join(__dirname,'test-valid.mp4'));
  await listening.getByRole('button',{name:'↑ 上传解析'}).click();
  await page.waitForFunction(()=>document.querySelector('[data-id=listening] strong').textContent==='已完成',null,{timeout:90000});
  assert.equal(await page.locator('#publish').isEnabled(),true);
  await page.locator('#previewTab').click();
  await page.locator('#previewAction').selectOption('neutral_explain');
  await page.locator('#connect').click();
  await page.waitForFunction(()=>document.querySelector('#connectionState').textContent==='已连接',null,{timeout:30000});
  await page.waitForFunction(()=>document.querySelector('#liveVideo').videoWidth>0);
  const pixels = await page.evaluate(()=>{
    const canvas=document.createElement('canvas');canvas.width=100;canvas.height=100;
    const ctx=canvas.getContext('2d');ctx.drawImage(document.querySelector('#liveVideo'),0,0,100,100);
    const data=ctx.getImageData(0,0,100,100).data;
    let total=0;for(let i=0;i<data.length;i+=4)total+=data[i]+data[i+1]+data[i+2];return total;
  });
  assert.ok(pixels>10000,'Video canvas should contain nonblank pixels');
  await page.locator('#previewAction').selectOption('listening');
  await page.waitForFunction(()=>document.querySelector('#sessionInfo').textContent.includes('__listening'),null,{timeout:30000});
  await page.waitForFunction(()=>document.querySelector('#connectionState').textContent==='已连接');
  await page.screenshot({path:path.join(__dirname,'test-live-preview.png'),fullPage:true});
  await page.locator('#disconnect').click();
  await page.locator('#materialsTab').click();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.screenshot({path:path.join(__dirname,'test-mobile.png'),fullPage:true});
  await page.locator('#newPackage').click();
  assert.equal(await page.locator('#createDialog').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  await page.locator('#closeDialog').click();
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({packageId,upload:'passed',invalid_fps:'rejected',retry:'passed',
                             live_preview:'nonblank',action_reconnect:'passed',mobile_overflow:false,pageErrors:errors}));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
